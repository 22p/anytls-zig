#!/bin/sh
# Build the arch-independent OpenWrt apk for the LuCI application.
#
#   scripts/make-luci-apk.sh <pkgver> <output.apk>
#
# The catalog is compiled from po/zh_Hans with scripts/po2lmo.py, which emits
# the same .lmo bytes as LuCI's po2lmo host tool.
#
# Unsigned package: install with `apk add --allow-untrusted <file>` or sign it
# with the key trusted by the image. apk v2 (tar.gz, apk-tools 2.x); images
# using apk-tools 3 need an SDK build from openwrt/luci/.../Makefile.

set -eu

pkgver=${1:?usage: make-luci-apk.sh <pkgver> <output.apk>}
output=${2:?usage: make-luci-apk.sh <pkgver> <output.apk>}

here=$(cd "$(dirname "$0")/.." && pwd)
app="$here/openwrt/luci/luci-app-anytls-zig"
tmp=$(mktemp -d /tmp/anytls-luci-apk.XXXXXX)
list=$(mktemp /tmp/anytls-luci-list.XXXXXX)
trap 'rm -rf "$tmp" "$list"' EXIT INT TERM

mkdir -p "$tmp/www/luci-static/resources/view/anytls-zig" \
	"$tmp/usr/share/luci/menu.d" \
	"$tmp/usr/share/rpcd/acl.d" \
	"$tmp/usr/lib/lua/luci/i18n"

cp "$app/htdocs/luci-static/resources/view/anytls-zig/settings.js" \
	"$tmp/www/luci-static/resources/view/anytls-zig/settings.js"
cp "$app/root/usr/share/luci/menu.d/luci-app-anytls-zig.json" \
	"$tmp/usr/share/luci/menu.d/luci-app-anytls-zig.json"
cp "$app/root/usr/share/rpcd/acl.d/luci-app-anytls-zig.json" \
	"$tmp/usr/share/rpcd/acl.d/luci-app-anytls-zig.json"
python3 "$here/scripts/po2lmo.py" "$app/po/zh_Hans/anytls-zig.po" \
	"$tmp/usr/lib/lua/luci/i18n/anytls-zig.zh_Hans.lmo"

find "$tmp" -type f -exec chmod 644 {} +
installed_size=$(find "$tmp" -type f -printf '%s\n' | awk '{s += $1} END {print s + 0}')

cat > "$tmp/.PKGINFO" <<EOF
# Generated by anytls-zig make-luci-apk.sh
pkgname = luci-app-anytls-zig
pkgver = $pkgver
pkgdesc = LuCI support for AnyTLS Zig
arch = all
size = $installed_size
origin = luci-app-anytls-zig
maintainer = anytls-zig contributors
license = MIT
depend = luci-base
depend = anytls-zig
EOF

( cd "$tmp" && find . -mindepth 1 -not -name '.PKGINFO' -printf '%P\n' | LC_ALL=C sort > "$list" )
( cd "$tmp" && tar --format=gnu --sort=name --mtime='@0' --owner=0 --group=0 \
	--numeric-owner --no-recursion -cf - .PKGINFO -T "$list" ) | gzip -9n > "$output"

echo "apk: $output ($installed_size bytes installed, arch all)"
