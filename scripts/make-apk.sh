#!/bin/sh
# Build an OpenWrt apk package from an already built binary.
#
#   scripts/make-apk.sh <binary> <openwrt-arch> <pkgver> <output.apk>
#
# Example:
#   scripts/make-apk.sh zig-out/bin/anytls-zig mipsel_24kc 0.1.0-r1 \
#       anytls-zig_0.1.0-r1_mipsel_24kc.apk
#
# This is the tar.gz apk v2 format used by apk-tools 2.x (e.g. OpenWrt 24.10
# with CONFIG_USE_APK). Images using apk-tools 3 (ADB format) should build the
# package with the OpenWrt SDK from openwrt/Makefile instead.
#
# The package is unsigned: install with `apk add --allow-untrusted <file>` or
# sign it with the key trusted by the target image. The payload is:
#   /usr/bin/anytls-zig
#   /etc/init.d/anytls-zig
#   /etc/config/anytls-zig        (mode 600: it contains the password)
#   /etc/anytls-zig/config.toml.example

set -eu

binary=${1:?usage: make-apk.sh <binary> <arch> <pkgver> <output.apk>}
arch=${2:?usage: make-apk.sh <binary> <arch> <pkgver> <output.apk>}
pkgver=${3:?usage: make-apk.sh <binary> <arch> <pkgver> <output.apk>}
output=${4:?usage: make-apk.sh <binary> <arch> <pkgver> <output.apk>}

[ -f "$binary" ] || {
	echo "missing binary: $binary" >&2
	exit 1
}

here=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d /tmp/anytls-apk.XXXXXX)
list=$(mktemp /tmp/anytls-apk-list.XXXXXX)
trap 'rm -rf "$tmp" "$list"' EXIT INT TERM

mkdir -p "$tmp/usr/bin" "$tmp/etc/init.d" "$tmp/etc/config" "$tmp/etc/anytls-zig"
cp "$binary" "$tmp/usr/bin/anytls-zig"
cp "$here/openwrt/files/anytls-zig.init" "$tmp/etc/init.d/anytls-zig"
cp "$here/openwrt/files/anytls-zig.config" "$tmp/etc/config/anytls-zig"
cp "$here/config/anytls-zig.toml" "$tmp/etc/anytls-zig/config.toml.example"

chmod 755 "$tmp/usr/bin/anytls-zig" "$tmp/etc/init.d/anytls-zig"
chmod 600 "$tmp/etc/config/anytls-zig"
chmod 644 "$tmp/etc/anytls-zig/config.toml.example"

installed_size=$(find "$tmp" -type f -printf '%s\n' | awk '{s += $1} END {print s + 0}')

cat > "$tmp/.PKGINFO" <<EOF
# Generated by anytls-zig make-apk.sh
pkgname = anytls-zig
pkgver = $pkgver
pkgdesc = AnyTLS client (protocol v2, TLS 1.3, static)
arch = $arch
size = $installed_size
origin = anytls-zig
maintainer = anytls-zig contributors
license = MIT
depend = ca-bundle
EOF

# Reproducible archive: .PKGINFO first, sorted entries, zeroed timestamps.
( cd "$tmp" && find . -mindepth 1 -not -name '.PKGINFO' -printf '%P\n' | LC_ALL=C sort > "$list" )
( cd "$tmp" && tar --format=gnu --sort=name --mtime='@0' --owner=0 --group=0 \
	--numeric-owner --no-recursion -cf - .PKGINFO -T "$list" ) | gzip -9n > "$output"

echo "apk: $output ($installed_size bytes installed, arch $arch)"
